export type PixelIconName = keyof typeof ICONS

export function PixelIcon({ name = "spark", className }: { name?: PixelIconName; className?: string }) {
  const rows = ICONS[name]
  return (
    <svg viewBox="0 0 9 9" className={cn("size-8", className)} fill="currentColor" shapeRendering="crispEdges" aria-hidden>
      {rows.flatMap((row, y) =>
        [...row].map((c, x) => (c === "#" ? <rect key={`${x}-${y}`} x={x} y={y} width="1" height="1" /> : null)),
      )}
    </svg>
  )
}
